import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = process.cwd();
const assessmentPath = 'content-drafts/crypto-module-tester-duration-neutral/assessment-authority.json';
const provenancePath = 'content-drafts/crypto-module-tester-duration-neutral/question-provenance.json';
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const hashFile = (p) => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, p))).digest('hex');
const assessment = read(assessmentPath);
const provenance = read(provenancePath);
const questions = assessment.questions;
const expectedIds = Array.from({ length: 120 }, (_, i) => `CMT-DN-Q${String(i + 1).padStart(3, '0')}`);
const failures = [];
const fail = (ok, message) => { if (!ok) failures.push(message); };
fail(Array.isArray(questions) && questions.length === 120, 'question count must be 120');
fail(provenance.question_authority_count === 1, 'question authority count must be one');
fail(JSON.stringify(provenance.question_ids) === JSON.stringify(expectedIds), 'question IDs must exactly bind current authority');
fail(new Set(provenance.question_ids).size === 120, 'provenance question IDs must be unique');
fail(provenance.question_set_hash === crypto.createHash('sha256').update(JSON.stringify(questions)).digest('hex'), 'question set hash mismatch');
fail(fs.existsSync(path.join(root, provenance.generator_path)), 'generator path missing');
fail(hashFile(provenance.generator_path) === provenance.generator_sha256, 'generator hash mismatch');
fail(/^[0-9a-f]{40}$/.test(provenance.authoring_commit), 'authoring commit format invalid');
fail(provenance.expression_origin === 'SECURIUM_ORIGINAL_SUPPORTED', 'originality status was upgraded or changed');
fail(provenance.rights_status === 'RIGHTS_SUPPORTED_WITH_PROVENANCE_LIMITATION', 'rights limitation missing');
fail(provenance.evidence_grade === 'B', 'evidence grade was upgraded or changed');
fail(provenance.source_boundary.question_authority === 0, 'restricted source became question authority');
fail(provenance.canonical_product_dependency_on_source_question_expression === 0, 'restricted expression dependency is nonzero');
fail(provenance.historical_boundary.role === 'EXCLUDED_FROM_PRODUCT_AUTHORITY', 'historical candidate boundary missing');
fail(provenance.no_question_payload_copy === true, 'provenance authority must not duplicate question payload');
fail(provenance.no_source_image_inspection === true, 'source image inspection boundary missing');
const result = { schema:'securium.crypto_module_tester.question_provenance.v1', status:failures.length?'FAIL':'PASS', failures, authority_path:assessmentPath, provenance_path:provenancePath, question_count:questions.length, duplicate_ids:questions.length-new Set(questions.map(q=>q.id)).size, semantic_hash:crypto.createHash('sha256').update(JSON.stringify(questions)).digest('hex'), generator_sha256:provenance.generator_sha256, restricted_source_question_authority:provenance.source_boundary.question_authority, historical_question_authority:0, no_payload_mutation:0 };
console.log(JSON.stringify(result, null, 2));
if (failures.length) process.exitCode = 1;
